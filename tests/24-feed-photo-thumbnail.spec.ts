/**
 * Playwright route spec — feed/home photo thumbnails
 * (tests/24-feed-photo-thumbnail.spec.ts).
 *
 * ── The defect this pins ───────────────────────────────────────
 *
 * The user reported: *"the report list should show the submitted
 * photo as thumbnail"*. On the City Activity feed the report rows
 * rendered a blank dark-green placeholder square where the citizen's
 * own submitted photo should have been.
 *
 * Root cause: a `TicketPhoto.url` stores whatever the uploader handed
 * the API, VERBATIM — and the DEFAULT upload path inlines the file
 * bytes as a `data:image/jpeg;base64,…` URL (no blob provider is
 * configured out of the box). Several surfaces guarded their
 * thumbnail with `photoUrl.startsWith('http')`, which matches only
 * the absolute-R2/S3 shape — so the inline `data:` URL fell through
 * to the "no photo" gradient.
 *
 * This spec drives the REAL flow: register a citizen, submit a report
 * with an inline data-URL photo, then assert the photo is actually
 * painted into the thumbnail slot on `/feed` and `/home`.
 *
 * The assertion is on the RENDERED PIXEL, not on a CSS string: we
 * read the thumbnail's pixel colour from the screenshot buffer and
 * assert it is the photo's distinctive colour, not the placeholder
 * gradient. A thumbnail that silently falls back to the gradient
 * fails this test.
 *
 * The photo below is a tiny 2×2 PNG whose pixels are pure magenta
 * (#FF00FF) — a colour that appears nowhere in the app's palette, so
 * it cannot be confused with the placeholder gradient, the surface
 * card, or the primary-soft tint.
 */

import { test, expect, APIRequestContext } from '@playwright/test';
import { loginAsCitizen } from './helpers/auth';

const BASE = process.env.BASE_URL ?? 'http://localhost:3000';

/**
 * The ids this spec posts against.
 *
 * The seed uses stable slugs (`city_dhaka_north`, `ward_14`,
 * `cat_streetlight`) in the dev store, but the REAL database assigns
 * Prisma CUIDs to every city / ward / category — the seed's ids are
 * only used by the in-memory dev store. So the ids are resolved from
 * the live API instead of hard-coded, which works against BOTH
 * backends.
 */
interface ResolvedIds {
  cityId: string;
  wardId: string;
  streetlightCategoryId: string;
  potholeCategoryId: string;
}

/**
 * Resolve a city, a ward and two categories from the public API.
 *
 * Prefers a category whose slug matches; falls back to positional
 * picks so the spec still runs if the slugs change.
 */
async function resolveIds(
  ctx: APIRequestContext,
): Promise<ResolvedIds> {
  const res = await ctx.get(`${BASE}/api/v1/activity/public?limit=50`);
  expect(res.status(), 'expected 200 from the public activity feed').toBe(200);
  const body = (await res.json()) as {
    tickets: Array<{
      cityId: string;
      wardId: string;
      categoryId: string;
    }>;
    categories: Array<{ id: string; slug: string }>;
  };

  const first = body.tickets[0];
  expect(
    first,
    'the feed must contain at least one ticket to resolve city/ward ids from',
  ).toBeTruthy();

  const bySlug = (slug: string) => body.categories.find((c) => c.slug === slug);
  const streetlight = bySlug('streetlight') ?? body.categories[0];
  const pothole =
    bySlug('pothole') ??
    body.categories.find((c) => c.id !== streetlight.id) ??
    streetlight;

  return {
    cityId: first.cityId,
    wardId: first.wardId,
    streetlightCategoryId: streetlight.id,
    potholeCategoryId: pothole.id,
  };
}

/**
 * A 2×2 PNG whose every pixel is opaque magenta (#FF00FF).
 *
 * Generated by drawing on a Chromium canvas and reading the PNG data
 * URL back — so the chunk structure is guaranteed valid (IHDR → IDAT
 * → IEND, with a valid CRC on each).
 *
 * Magenta is deliberately outside the app's palette (teal/green
 * primary, slate neutrals) so a pixel assertion cannot pass by
 * accident.
 *
 * DO NOT hand-edit this string. An earlier hand-built fixture was
 * truncated mid-IDAT (its base64 length was not a multiple of 4 and
 * it had no IEND chunk). Chromium is lenient enough to decode it
 * anyway and paint red-and-black garbage, so the test failed on a
 * colour mismatch with no decode error to explain it. `isValidPng`
 * below is the cheap guard against that class of mistake.
 */
const MAGENTA_PNG_2x2 =
  'iVBORw0KGgoAAAANSUhEUgAAAAIAAAACCAYAAABytg0kAAAAEklEQVR4AWL6z/D/PwgzMUABAAAA//96NbY1AAAABklEQVQDAE/4Bf+etxqlAAAAAElFTkSuQmCC';

const MAGENTA_DATA_URL = `data:image/png;base64,${MAGENTA_PNG_2x2}`;

/**
 * Reset the dev store, when it is running.
 *
 * Against the real database there is no reset — the rows from a
 * previous run are simply left in place. That is fine for this
 * spec: it locates its own row by the distinctive fixture note, so
 * leftover rows from earlier runs do not affect the assertions.
 */
async function devReset(ctx: APIRequestContext) {
  return ctx.post(`${BASE}/api/dev/reset`, {
    maxRedirects: 0,
    failOnStatusCode: false,
  });
}

/**
 * A cheap structural guard on the PNG fixture.
 *
 * A truncated PNG (missing IEND, base64 length not a multiple of 4)
 * is still "decodable" by Chromium, which silently paints garbage.
 * This catches that class of mistake at the source.
 */
function isValidPng(base64: string): boolean {
  if (base64.length % 4 !== 0) return false;
  const bytes = Buffer.from(base64, 'base64');
  // 8-byte PNG signature.
  const sig = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);
  if (!bytes.subarray(0, 8).equals(sig)) return false;
  // The last chunk must be IEND (its type starts at bytes.length - 8).
  return bytes.subarray(bytes.length - 8, bytes.length - 4).toString('ascii') === 'IEND';
}

/**
 * The average RGB of the thumbnail's SOURCE pixels, read from
 * inside the page via a canvas.
 *
 * We do not assert on the DOM's `src` attribute alone — a URL can
 * be present on the element while the browser still fails to paint
 * it (a broken data URL, a 404 blob path, a CSS `url()` that the
 * parser rejected). Reading the ACTUAL pixels is the only assertion
 * that proves the citizen SEES their photo.
 *
 * We read the `<img>` element's own `src` and decode it through a
 * canvas — this yields EXACT pixel values. (Screenshotting the
 * element and averaging instead would mix in the CSS border and the
 * browser's upscaling of a 2×2 image, which muddies the reading.)
 */
async function averageRgbOfImage(
  page: import('@playwright/test').Page,
  locator: import('@playwright/test').Locator,
): Promise<{ r: number; g: number; b: number }> {
  const src = await locator.getAttribute('src');
  if (!src) throw new Error('thumbnail has no src');
  return page.evaluate(async (url) => {
    const img = new Image();
    img.src = url;
    await img.decode();
    const canvas = document.createElement('canvas');
    canvas.width = img.naturalWidth;
    canvas.height = img.naturalHeight;
    const ctx = canvas.getContext('2d');
    if (!ctx) throw new Error('no 2d context');
    ctx.drawImage(img, 0, 0);
    const { data } = ctx.getImageData(0, 0, canvas.width, canvas.height);
    let r = 0;
    let g = 0;
    let b = 0;
    const n = data.length / 4;
    for (let i = 0; i < data.length; i += 4) {
      r += data[i];
      g += data[i + 1];
      b += data[i + 2];
    }
    return { r: r / n, g: g / n, b: b / n };
  }, src);
}

async function seedCitizenTicketWithPhoto(
  ctx: APIRequestContext,
  ids: ResolvedIds,
): Promise<string> {
  /*
   * The coordinates are jittered per call.
   *
   * `POST /api/tickets` runs a DEDUP check (50m radius) and, on a
   * match, answers **200** with `dedup_match: true` instead of
   * **201** — no ticket is created. Against a persistent database
   * (the local Postgres does not reset between runs) a fixed
   * coordinate would therefore match the previous run's fixture and
   * the second run would fail with "expected 201, got 200". The
   * jitter keeps each run's fixture outside the previous one's
   * dedup radius while staying inside the Dhaka bounding box.
   */
  const jitter = () => (Math.random() - 0.5) * 0.004;

  const resp = await ctx.post(`${BASE}/api/tickets`, {
    data: {
      cityId: ids.cityId,
      wardId: ids.wardId,
      categoryId: ids.streetlightCategoryId,
      note: 'Streetlight out — thumbnail regression fixture',
      locationLat: 23.789 + jitter(),
      locationLng: 90.4075 + jitter(),
      locationLabel: 'Mirpur 14',
      locationLabelBn: 'মিরপুর ১৪',
      photoUrls: [MAGENTA_DATA_URL],
    },
  });
  expect(
    resp.status(),
    `expected 201, got ${resp.status()} — ${await resp.text()}`,
  ).toBe(201);
  const body = (await resp.json()) as { ticket: { id: string } };
  return body.ticket.id;
}

test.describe('report-list photo thumbnail', () => {
  test('the PNG fixture is structurally valid', () => {
    // A truncated PNG is silently salvaged by Chromium into garbage
    // pixels, which turns a fixture mistake into a baffling
    // colour-mismatch failure. Guard the fixture itself.
    expect(
      isValidPng(MAGENTA_PNG_2x2),
      'the magenta PNG fixture must be a complete, well-formed PNG',
    ).toBe(true);
  });

  test('the feed renders the submitted photo in the row thumbnail', async ({
    page,
  }) => {
    // `page.request` shares the BrowserContext's cookie jar, so the
    // session established here is carried by the subsequent
    // `page.goto`. A detached `request.newContext()` would seed the
    // data but leave the BROWSER anonymous — and both `/feed` and
    // `/home` gate on an authenticated session.
    //
    // `loginAsCitizen` works against BOTH backends: the dev store
    // (`/api/dev/login`) when it is running, and the real
    // register → OTP → verify flow when it is not.
    await devReset(page.request);
    await loginAsCitizen(page);
    const ids = await resolveIds(page.request);
    await seedCitizenTicketWithPhoto(page.request, ids);

    await page.goto(`${BASE}/feed`, { waitUntil: 'networkidle' });

    /*
     * Scope to THIS run's row.
     *
     * Against a persistent database (the local Postgres does not
     * reset between runs) previous runs' fixtures are still in the
     * feed, so the fixture text matches several rows. `getByText`
     * in strict mode then fails with "resolved to N elements". The
     * first matching row is the newest — this run's — because the
     * feed is ordered newest-first.
     */
    const row = page
      .locator('a[href^="/reports/"]')
      .filter({ hasText: 'Streetlight out — thumbnail regression fixture' })
      .first();
    await expect(row).toBeVisible();

    // Locate the thumbnail: the <img> inside that row.
    // The fix renders an <img> (with the photo) when a photo exists;
    // the no-photo state is a placeholder <div> with NO <img>.
    const thumb = row.locator('img');
    await expect(thumb).toHaveCount(1);

    // The element must carry the inline data URL as its source.
    const src = await thumb.getAttribute('src');
    expect(src, 'thumbnail should carry the inline data URL').toContain(
      'data:image/png;base64,',
    );

    // AND the pixels must actually be painted. Decode the thumbnail's
    // own source and assert the average colour is magenta.
    const box = await thumb.boundingBox();
    expect(box, 'thumbnail should have a layout box').not.toBeNull();
    const rgb = await averageRgbOfImage(page, thumb);

    // Magenta is (255, 0, 255). The placeholder gradient is a
    // teal/slate tint — nowhere near this.
    expect(
      rgb.r,
      `thumbnail should be magenta-ish, got rgb(${rgb.r},${rgb.g},${rgb.b})`,
    ).toBeGreaterThan(180);
    expect(
      rgb.b,
      `thumbnail should be magenta-ish, got rgb(${rgb.r},${rgb.g},${rgb.b})`,
    ).toBeGreaterThan(180);
    expect(
      rgb.g,
      `thumbnail should be magenta-ish, got rgb(${rgb.r},${rgb.g},${rgb.b})`,
    ).toBeLessThan(90);
  });

  test('the home activity list renders the submitted photo thumbnail', async ({
    page,
  }) => {
    await devReset(page.request);
    await loginAsCitizen(page);
    const ids = await resolveIds(page.request);
    await seedCitizenTicketWithPhoto(page.request, ids);

    await page.goto(`${BASE}/home`, { waitUntil: 'networkidle' });

    // Scoped to this run's row — see the note in the feed test about
    // leftover fixtures in a persistent database.
    const row = page
      .locator('a[href^="/reports/"]')
      .filter({ hasText: 'Streetlight out — thumbnail regression fixture' })
      .first();
    await expect(row).toBeVisible();

    const thumb = row.locator('img');
    await expect(thumb).toHaveCount(1);

    const src = await thumb.getAttribute('src');
    expect(src).toContain('data:image/png;base64,');
  });

  test('a report with no photo falls back to the placeholder, not a broken image', async ({
    page,
  }) => {
    await devReset(page.request);
    await loginAsCitizen(page);
    const ids = await resolveIds(page.request);
    // Jittered for the same dedup reason as the photo fixture above —
    // a fixed coordinate matches a previous run's ticket and the
    // route answers 200 `dedup_match` instead of creating one.
    const jitter = () => (Math.random() - 0.5) * 0.004;
    const resp = await page.request.post(`${BASE}/api/tickets`, {
      data: {
        cityId: ids.cityId,
        wardId: ids.wardId,
        categoryId: ids.potholeCategoryId,
        note: 'No photo attached — placeholder regression fixture',
        locationLat: 23.789 + jitter(),
        locationLng: 90.4075 + jitter(),
        photoUrls: [],
      },
    });
    expect(
      resp.status(),
      `expected 201, got ${resp.status()} — ${await resp.text()}`,
    ).toBe(201);

    await page.goto(`${BASE}/feed`, { waitUntil: 'networkidle' });

    // Scoped to this run's row — see the note in the feed test about
    // leftover fixtures in a persistent database.
    const row = page
      .locator('a[href^="/reports/"]')
      .filter({ hasText: 'No photo attached' })
      .first();
    await expect(row).toBeVisible();

    // The no-photo row must NOT contain an <img> — the placeholder
    // is a <div>. A stray <img> with an empty src would render the
    // browser's broken-image glyph.
    await expect(row.locator('img')).toHaveCount(0);

    // …and it must render the shared "no photo" empty state (dashed
    // border + camera glyph), NOT the old bare gradient square.
    const placeholder = row.locator('[data-testid="photo-placeholder"]');
    await expect(placeholder).toHaveCount(1);
  });
});
